// Generates every web/PWA brand asset from the traced emblem paths.
// Run: node scripts/generate-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';

const YELLOW = '#F8F400';
const INK = '#0a0a0a';
const { yellow, white } = JSON.parse(fs.readFileSync('scripts/.logo-paths.json', 'utf8'));

const emblem = ({ bg = INK, d = YELLOW, a = '#ffffff' } = {}) =>
  `<circle cx="512" cy="512" r="512" fill="${bg}"/>` +
  `<path fill-rule="evenodd" fill="${d}" d="${yellow}"/>` +
  `<path fill-rule="evenodd" fill="${a}" d="${white}"/>`;

const svgDoc = (inner, vb = 1024) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${vb} ${vb}">${inner}</svg>`;

// emblem centred on a square tile; scale = emblem diameter / tile size
const tile = (scale, tileBg, opts) => {
  const s = scale, off = (1024 * (1 - s)) / 2;
  const bg = tileBg ? `<rect width="1024" height="1024" fill="${tileBg}"/>` : '';
  return svgDoc(`${bg}<g transform="translate(${off} ${off}) scale(${s})">${emblem(opts)}</g>`);
};

const out = (...p) => path.join(...p);
fs.mkdirSync('public/icons', { recursive: true });
fs.mkdirSync('public/brand', { recursive: true });

const png = (svg, size, file) => sharp(Buffer.from(svg)).resize(size, size).png({ compressionLevel: 9 }).toFile(file);

// Vector sources
const plain = svgDoc(emblem());
fs.writeFileSync('public/brand/emblem.svg', plain);
fs.writeFileSync('src/app/icon.svg', plain);
// Monochrome (thermal-printer friendly) emblem
fs.writeFileSync('public/brand/emblem-mono.svg', svgDoc(emblem({ bg: '#000', d: '#fff', a: '#fff' })));

// PWA icons: "any" (transparent corners) + "maskable" (full-bleed, inside 80% safe zone)
for (const size of [72, 96, 128, 144, 152, 192, 384, 512]) {
  await png(plain, size, out('public/icons', `icon-${size}.png`));
}
for (const size of [192, 512]) {
  await png(tile(0.74, INK), size, out('public/icons', `maskable-${size}.png`));
}
// Apple touch icon (iOS ignores transparency -> solid tile)
await png(tile(0.82, INK), 180, 'src/app/apple-icon.png');
await png(plain, 1024, 'public/brand/emblem-1024.png');

// favicon.ico: PNG-compressed entries 16/32/48
const icoSizes = [16, 32, 48];
const bufs = await Promise.all(icoSizes.map((s) => sharp(Buffer.from(plain)).resize(s, s).png().toBuffer()));
const header = Buffer.alloc(6 + 16 * bufs.length);
header.writeUInt16LE(0, 0); header.writeUInt16LE(1, 2); header.writeUInt16LE(bufs.length, 4);
let offset = header.length;
bufs.forEach((b, i) => {
  const e = 6 + i * 16, s = icoSizes[i];
  header.writeUInt8(s, e); header.writeUInt8(s, e + 1); header.writeUInt8(0, e + 2); header.writeUInt8(0, e + 3);
  header.writeUInt16LE(1, e + 4); header.writeUInt16LE(32, e + 6);
  header.writeUInt32LE(b.length, e + 8); header.writeUInt32LE(offset, e + 12);
  offset += b.length;
});
fs.writeFileSync('src/app/favicon.ico', Buffer.concat([header, ...bufs]));

// Open Graph / social card 1200x630
const og = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <defs>
    <radialGradient id="g" cx="0.3" cy="0.5" r="0.8"><stop offset="0" stop-color="#2a2800"/><stop offset="1" stop-color="#050505"/></radialGradient>
    <pattern id="grid" width="40" height="40" patternUnits="userSpaceOnUse"><path d="M40 0H0V40" fill="none" stroke="#ffffff" stroke-opacity="0.04"/></pattern>
  </defs>
  <rect width="1200" height="630" fill="url(#g)"/><rect width="1200" height="630" fill="url(#grid)"/>
  <circle cx="270" cy="315" r="176" fill="none" stroke="${YELLOW}" stroke-opacity="0.35" stroke-width="3"/><g transform="translate(110 155) scale(0.3125)">${emblem()}</g>
  <text x="480" y="300" font-family="Segoe UI, Arial, sans-serif" font-size="78" font-weight="800" fill="#ffffff">Darkroom</text>
  <text x="480" y="385" font-family="Segoe UI, Arial, sans-serif" font-size="78" font-weight="800" fill="${YELLOW}">Arcade</text>
  <text x="482" y="445" font-family="Segoe UI, Arial, sans-serif" font-size="22" fill="#a3a3a3" letter-spacing="4">GAMING SESSIONS · RECEIPTS · REPORTS</text>
</svg>`;
await sharp(Buffer.from(og)).png().toFile('src/app/opengraph-image.png');

console.log('Brand assets generated.');

// Inline paths for the animated <Emblem /> component
fs.writeFileSync(
  'src/components/emblem-paths.ts',
  `// Generated by scripts/generate-icons.mjs — do not edit.\nexport const EMBLEM_D = ${JSON.stringify(yellow)};\nexport const EMBLEM_A = ${JSON.stringify(white)};\n`,
);
